/** Native PostgreSQL fixture intentionally omits unrelated legacy User and emergency columns. */
@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Import({UserServiceImpl.class, AvailabilityScheduleService.class,
        AvailabilityAccountRepository.class, LegacyAvailabilityRepository.class, AvailabilityConfiguration.class,
        ProfileAvailabilityPostgresTest.FrozenTime.class})
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@EnabledIfSystemProperty(named = "ba33.pg.enabled", matches = "true")
class ProfileAvailabilityPostgresTest {
    @TestConfiguration
    static class FrozenTime {
        @Bean @Primary Clock fixedAvailabilityClock() {
            return Clock.fixed(Instant.parse("2026-07-06T12:00:00Z"), ZoneOffset.UTC);
        }
    }

    @DynamicPropertySource
    static void database(DynamicPropertyRegistry properties) {
        PostgresTestDatabase.configure(properties, "ba33_t1");
    }

    @SpyBean JdbcTemplate jdbc;
    @Autowired UserServiceImpl users;

    @BeforeEach
    void fixture() {
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS ba33_t1");
        jdbc.execute("DROP TABLE IF EXISTS user_availability");
        jdbc.execute("DROP TABLE IF EXISTS volunteer_details");
        jdbc.execute("DROP TABLE IF EXISTS users");
        jdbc.execute("""
                CREATE TABLE users (
                    user_id varchar(64) PRIMARY KEY,
                    time_zone varchar(100),
                    primary_email_address varchar(255),
                    promotion_wizard_stage integer,
                    promotion_wizard_last_updated_at timestamp without time zone
                )
                """);
        jdbc.execute("""
                CREATE TABLE user_availability (
                    user_availability_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id varchar(64) NOT NULL REFERENCES users(user_id),
                    day_of_week varchar(10) NOT NULL,
                    start_time timestamp without time zone NOT NULL,
                    end_time timestamp without time zone NOT NULL,
                    last_updated_at timestamp without time zone
                )
                """);
        jdbc.update("INSERT INTO users(user_id,time_zone,primary_email_address,promotion_wizard_stage) VALUES (?,?,?,?)",
                "SID-T1", "UTC", "profile@example.test", 3);
        jdbc.execute("""
                CREATE TABLE volunteer_details (user_id varchar(64) PRIMARY KEY REFERENCES users(user_id),
                    availability_days jsonb, availability_times jsonb)
                """);
    }

    @Test
    void profileScheduleRoundTripsWithoutHydratingLegacyUserOrEmergencyColumns() {
        var saved = users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "Asia/Kolkata",
                List.of(new AvailabilitySlotRequest("Monday", "09:00", "17:00")), null, null, null));
        var loaded = users.getAvailability("SID-T1");
        assertThat(loaded).usingRecursiveComparison().ignoringFields("lastUpdatedAt").isEqualTo(saved);
        assertThat(loaded.getLastUpdatedAt()).isNotNull();
        assertThat(loaded.getLastUpdatedAt()).isEqualTo(LocalDateTime.of(2026, 7, 6, 12, 0));
        assertThat(loaded.getTimezone()).isEqualTo("Asia/Kolkata");
        assertThat(loaded.getSlots()).extracting(AvailabilitySlotResponse::getFrequency,
                        AvailabilitySlotResponse::getStartTime, AvailabilitySlotResponse::getEndTime)
                .containsExactly(tuple("Monday", "09:00", "17:00"));
    }

    @Test
    void groupedOvernightAndDeduplicatedSchedulesCanBeReplacedAndCleared() {
        var saved = users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "America/Chicago", List.of(
                new AvailabilitySlotRequest("Weekdays", "09:00", "17:00"),
                new AvailabilitySlotRequest("Monday", "09:00", "17:00"),
                new AvailabilitySlotRequest("Saturday", "22:00", "02:00")), true, "2026-12-20", "2026-12-31"));
        assertThat(users.getAvailability("SID-T1")).isEqualTo(saved);
        assertThat(saved.getSlots()).extracting(AvailabilitySlotResponse::getFrequency,
                        AvailabilitySlotResponse::getStartTime, AvailabilitySlotResponse::getEndTime)
                .containsExactly(tuple("Weekdays", "09:00", "17:00"), tuple("Saturday", "22:00", "02:00"));
        users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "Asia/Kolkata",
                List.of(new AvailabilitySlotRequest("Everyday", "08:00", "10:00")), null, null, null));
        assertThat(users.getAvailability("SID-T1").getSlots()).extracting(AvailabilitySlotResponse::getFrequency,
                        AvailabilitySlotResponse::getStartTime, AvailabilitySlotResponse::getEndTime)
                .containsExactly(tuple("Everyday", "08:00", "10:00"));
        users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "Asia/Kolkata", List.of(), null, null, null));
        assertThat(users.getAvailability("SID-T1").getSlots()).isEmpty();
    }

    @Test
    void invalidReplacementLeavesThePreviouslySavedScheduleAndTimezoneIntact() {
        var before = users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "UTC",
                List.of(new AvailabilitySlotRequest("Monday", "09:00", "17:00")), null, null, null));
        assertThatThrownBy(() -> users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "Asia/Kolkata",
                List.of(new AvailabilitySlotRequest("Monday", "09:00", "17:00"),
                        new AvailabilitySlotRequest("Monday", "10:00", "12:00")), null, null, null)))
                .isInstanceOf(IllegalArgumentException.class);
        assertThat(users.getAvailability("SID-T1")).isEqualTo(before);
    }

    @Test
    @SuppressWarnings({"rawtypes", "unchecked"})
    void readingDuringAConcurrentTimezoneReplacementReturnsOneConsistentSchedule() throws Exception {
        var before = users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "UTC",
                List.of(new AvailabilitySlotRequest("Monday", "09:00", "17:00")), null, null, null));
        CountDownLatch accountRead = new CountDownLatch(1);
        CountDownLatch replacementCommitted = new CountDownLatch(1);
        // Instrument the JDBC boundary, not application methods: pause after the first real DB read.
        doAnswer(invocation -> {
            Object result = invocation.callRealMethod();
            String sql = invocation.getArgument(0);
            if (Thread.currentThread().getName().equals("ba33-snapshot-reader") && sql.contains("FROM users")) {
                accountRead.countDown();
                if (!replacementCommitted.await(10, TimeUnit.SECONDS)) {
                    throw new AssertionError("Concurrent replacement did not commit");
                }
            }
            return result;
        }).when(jdbc).query(anyString(), any(RowMapper.class), any(Object[].class));
        var executor = Executors.newSingleThreadExecutor(r -> new Thread(r, "ba33-snapshot-reader"));
        try {
            var reading = executor.submit(() -> users.getAvailability("SID-T1"));
            assertThat(accountRead.await(10, TimeUnit.SECONDS)).isTrue();
            var replacement = users.updateAvailability(new UpdateAvailabilityRequest("SID-T1", "Asia/Kolkata",
                    List.of(new AvailabilitySlotRequest("Tuesday", "10:00", "11:00")), null, null, null));
            replacementCommitted.countDown();
            assertThat(reading.get(10, TimeUnit.SECONDS)).isEqualTo(before);
            assertThat(users.getAvailability("SID-T1")).isEqualTo(replacement);
        } finally {
            replacementCommitted.countDown();
            executor.shutdownNow();
        }
    }
}
